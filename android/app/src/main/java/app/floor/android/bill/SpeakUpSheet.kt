/**
 * Speak up (round 11, section C; iOS `SpeakUpSheet`): a message about this bill to one of **your
 * own** members — offices discard mail from outside the district — that the person finishes and
 * sends through the office's own form, or a call script.
 *
 * The product calls, kept here: no stance is ever chosen for you; the text is fixed, with only the
 * bill's facts ([SpeakUpTemplate]), no AI and no talking points; nothing is stored or sent by Floor.
 * The message lives in this sheet's state and goes when it closes. "Copy & open form" puts it on
 * the clipboard and opens the office's form in the browser; "Call" opens the dialer with the number.
 *
 * `initialStance`, `recipientId`, `startCalling` and `contacts` exist for the screenshot tests,
 * which draw the mock's states; the app opens the sheet with no stance chosen, always.
 *
 * @param contact a member's office contact, fetched when they become the recipient.
 */
@Composable
fun SpeakUpSheet(
    facts: BillFacts,
    delegation: Delegation?,
    contact: suspend (Member) -> MemberContact?,
    initialStance: Stance? = null,
    recipientId: String? = null,
    startCalling: Boolean = false,
    contacts: Map<String, MemberContact> = emptyMap(),
    /** "Set your district": closes the sheet and opens onboarding; null draws no button. */
    onSetDistrict: (() -> Unit)? = null,
) {
    val recipients = remember(delegation) { delegation?.let(::recipients).orEmpty() }
    var recipient by remember { mutableStateOf(recipients.firstOrNull { it.bioguideId == recipientId } ?: recipients.firstOrNull()) }
    var stance by remember { mutableStateOf(initialStance) }
    val initialText = remember {
        val first = recipient
        if (first != null && delegation != null && initialStance != null) {
            SpeakUpTemplate.message(first, delegation.district, facts, initialStance)
        } else {
            ""
        }
    }
    var text by remember { mutableStateOf(initialText) }
    // The text as last generated, to tell an edited message from an untouched one.
    var generated by remember { mutableStateOf(initialText) }
    val known = remember { mutableStateMapOf<String, MemberContact>().apply { putAll(contacts) } }
    var calling by remember { mutableStateOf(startCalling) }
    var copied by remember { mutableStateOf(false) }

    LaunchedEffect(recipient?.bioguideId) {
        val member = recipient ?: return@LaunchedEffect
        if (known[member.bioguideId] == null) contact(member)?.let { known[member.bioguideId] = it }
    }

    fun chooseRecipient(member: Member, district: District) {
        val old = recipient
        recipient = member
        copied = false
        val chosen = stance ?: return
        val next = SpeakUpTemplate.message(member, district, facts, chosen)
        text = if (text == generated || old == null) {
            next
        } else {
            // Edited: swap only the greeting and where-you-live line, keeping the person's words.
            text.replace(SpeakUpTemplate.greeting(old), SpeakUpTemplate.greeting(member))
                .replace(SpeakUpTemplate.residence(old, district), SpeakUpTemplate.residence(member, district))
        }
        generated = next
    }

    fun chooseStance(choice: Stance, district: District) {
        val member = recipient ?: return
        val old = stance
        stance = choice
        copied = false
        val next = SpeakUpTemplate.message(member, district, facts, choice)
        val swapped = if (old != null && text != generated) SpeakUpTemplate.restanced(text, old, choice) else null
        if (swapped != null) {
            text = swapped
        } else if (old == null || text == generated) {
            text = next
        }
        generated = next
    }

    Column(
        Modifier
            .fillMaxWidth()
            .background(Palette.ground)
            .verticalScroll(rememberScrollState())
            .padding(start = 16.dp, end = 16.dp, top = 20.dp, bottom = 24.dp),
        verticalArrangement = Arrangement.spacedBy(10.dp),
    ) {
        val member = recipient
        if (calling && member != null && delegation != null) {
            CallView(member, delegation.district, facts, stance, known[member.bioguideId]) { calling = false }
        } else {
            Text(
                "SPEAK UP · ${facts.citation.uppercase()}",
                style = FloorType.headline(22f),
                color = Palette.text,
                modifier = Modifier.semantics { heading() },
            )
            if (delegation == null) {
                NoDistrict(onSetDistrict)
            } else {
                SheetLabel("TO · YOUR MEMBERS")
                Chips(recipients.map { it.shortName }, recipients.indexOfFirst { it.bioguideId == member?.bioguideId }) {
                    chooseRecipient(recipients[it], delegation.district)
                }
                SheetLabel("YOUR VIEW · YOU CHOOSE")
                Chips(Stance.entries.map { it.chip }, stance?.ordinal ?: -1) {
                    chooseStance(Stance.entries[it], delegation.district)
                }
                Message(stance != null, text) { text = it }
                WriteActions(
                    member, known[member?.bioguideId], text, stance != null, copied,
                    onCopied = { copied = true }, onCall = { calling = true },
                )
                Text(
                    "Floor fills in only the bill's facts. Nothing is picked for you, and nothing is sent or stored.",
                    style = FloorType.text(10f),
                    color = Palette.textMuted,
                )
            }
        }
    }
}

/** Your representative, then your senators. */
fun recipients(delegation: Delegation): List<Member> =
    delegation.members.filter { it.chamber == Chamber.HOUSE } + delegation.members.filter { it.chamber == Chamber.SENATE }

@Composable
private fun NoDistrict(onSetDistrict: (() -> Unit)?) {
    val colors = Palette
    Column(
        Modifier.dashedPanel(colors.raised, Color.Transparent, 12.dp).padding(12.dp),
        verticalArrangement = Arrangement.spacedBy(8.dp),
    ) {
        Text("SET YOUR DISTRICT FIRST", style = FloorType.label(12f).copy(letterSpacing = 1.2.sp), color = colors.textMuted)
        Text(
            "Offices count mail and calls only from their own constituents, so Speak up writes only to your " +
                "representative and your two senators. Floor doesn't know your district yet.",
            style = FloorType.text(13f),
            color = colors.textSecondary,
        )
        if (onSetDistrict != null) {
            val shape = RoundedCornerShape(9.dp)
            Text(
                "SET YOUR DISTRICT",
                style = FloorType.label(14f).copy(letterSpacing = 0.6.sp),
                color = colors.ground,
                modifier = Modifier.clip(shape).background(colors.threshold, shape)
                    .clickable(role = androidx.compose.ui.semantics.Role.Button, onClick = onSetDistrict)
                    .padding(horizontal = 12.dp, vertical = 10.dp),
            )
        }
        Text("You can still call any member from the Contact tab on their page.", style = FloorType.text(11f), color = colors.textMuted)
    }
}

@Composable
private fun Message(chosen: Boolean, text: String, onEdit: (String) -> Unit) {
    val colors = Palette
    val shape = RoundedCornerShape(12.dp)
    if (!chosen) {
        Text(
            "Pick your view and the message appears here, with the bill's facts filled in.",
            style = FloorType.text(11.5f),
            color = colors.textMuted,
            modifier = Modifier.dashedPanel(colors.raised, Color.Transparent, 12.dp).defaultMinSize(minHeight = 120.dp).padding(12.dp),
        )
    } else {
        BasicTextField(
            value = text,
            onValueChange = onEdit,
            textStyle = FloorType.text(12.5f).copy(color = colors.text, lineHeight = 17.5.sp),
            cursorBrush = SolidColor(colors.accent),
            modifier = Modifier
                .fillMaxWidth()
                .defaultMinSize(minHeight = 230.dp)
                .clip(shape)
                .background(colors.widget, shape)
                .border(1.dp, colors.panelBorder, shape)
                .padding(11.dp)
                .semantics { contentDescription = "Message. Edit it as you like; replace the bracketed lines with your own words." },
        )
    }
}

@Composable
private fun WriteActions(
    member: Member?,
    contact: MemberContact?,
    text: String,
    chosen: Boolean,
    copied: Boolean,
    onCopied: () -> Unit,
    onCall: () -> Unit,
) {
    val context = LocalContext.current
    val form = member?.let { SpeakUpTemplate.formUrl(it, contact) }
    Column(verticalArrangement = Arrangement.spacedBy(6.dp)) {
        Row(horizontalArrangement = Arrangement.spacedBy(6.dp)) {
            SheetButton(if (copied) "COPIED ✓" else "COPY & OPEN FORM", filled = true, enabled = chosen && form != null) {
                copyToClipboard(context, text)
                onCopied()
                if (form != null) open(context, form)
            }
            SheetButton("CALL INSTEAD", filled = false, enabled = member != null, onClick = onCall)
        }
        if (member != null && member.chamber == Chamber.HOUSE && contact?.contactForm == null) {
            Text(
                "No form listed for this office, so this opens the House's \"Write Your Representative\" form, which checks your ZIP.",
                style = FloorType.text(10f),
                color = Palette.textMuted,
            )
        }
    }
}

@Composable
private fun CallView(member: Member, district: District, facts: BillFacts, stance: Stance?, contact: MemberContact?, onDone: () -> Unit) {
    val colors = Palette
    val context = LocalContext.current
    val shape = RoundedCornerShape(12.dp)
    Text(
        "CALL ${member.shortName.uppercase()}",
        style = FloorType.headline(22f),
        color = colors.text,
        modifier = Modifier.semantics { heading() },
    )
    Row(
        Modifier
            .fillMaxWidth()
            .clip(shape)
            .background(colors.panel, shape)
            .border(1.dp, colors.panelBorder, shape)
            .padding(horizontal = 11.dp, vertical = 9.dp),
        verticalAlignment = Alignment.CenterVertically,
        horizontalArrangement = Arrangement.spacedBy(10.dp),
    ) {
        Icon(
            painterResource(R.drawable.ic_phone),
            contentDescription = null,
            tint = colors.threshold,
            modifier = Modifier.clip(RoundedCornerShape(8.dp)).background(colors.chip).padding(6.dp).size(16.dp),
        )
        Column(verticalArrangement = Arrangement.spacedBy(1.dp)) {
            Text(contact?.phone ?: "No phone number listed", style = FloorType.text(13f, FontWeight.Bold), color = colors.text)
            Text("Washington office", style = FloorType.text(10.5f, FontWeight.Medium), color = colors.textMuted)
        }
    }
    SheetLabel("WHAT TO SAY · ABOUT 30 SECONDS")
    Column(
        Modifier
            .fillMaxWidth()
            .clip(shape)
            .background(colors.widget, shape)
            .border(1.dp, colors.panelBorder, shape)
            .padding(10.dp),
        verticalArrangement = Arrangement.spacedBy(6.dp),
    ) {
        SpeakUpTemplate.callScript(member, district, facts, stance).forEach {
            Text(it, style = FloorType.text(12f), color = colors.text)
        }
    }
    Row(horizontalArrangement = Arrangement.spacedBy(6.dp)) {
        val tel = SpeakUpTemplate.telUrl(contact?.phone)
        // The dialer, with the number filled in: the person places the call, not Floor.
        SheetButton("CALL", filled = true, enabled = tel != null) { if (tel != null) open(context, tel, Intent.ACTION_DIAL) }
        SheetButton("DONE", filled = false, enabled = true, onClick = onDone)
    }
}

@Composable
private fun SheetLabel(text: String) {
    Text(
        text,
        style = FloorType.label(10.5f).copy(letterSpacing = 1.sp),
        color = Palette.textMuted,
        modifier = Modifier.padding(top = 2.dp).semantics { heading() },
    )
}

@OptIn(ExperimentalLayoutApi::class)
@Composable
private fun Chips(titles: List<String>, selected: Int, onChoose: (Int) -> Unit) {
    val colors = Palette
    FlowRow(horizontalArrangement = Arrangement.spacedBy(5.dp), verticalArrangement = Arrangement.spacedBy(5.dp)) {
        titles.forEachIndexed { index, title ->
            val on = index == selected
            val shape = RoundedCornerShape(10.dp)
            Text(
                title,
                style = FloorType.text(11.5f, FontWeight.SemiBold),
                color = if (on) colors.ground else colors.textSecondary,
                modifier = Modifier
                    .clip(shape)
                    .background(if (on) colors.text else Color.Transparent, shape)
                    .border(1.dp, if (on) Color.Transparent else colors.raised, shape)
                    .clickable(role = Role.RadioButton) { onChoose(index) }
                    .semantics { this.selected = on }
                    .padding(horizontal = 9.dp, vertical = 6.dp),
            )
        }
    }
}

@Composable
private fun RowScope.SheetButton(title: String, filled: Boolean, enabled: Boolean, onClick: () -> Unit) {
    val colors = Palette
    val shape = RoundedCornerShape(9.dp)
    Text(
        title,
        style = FloorType.label(13f).copy(letterSpacing = 0.6.sp, textAlign = androidx.compose.ui.text.style.TextAlign.Center),
        color = if (filled) colors.ground else colors.text,
        modifier = Modifier
            .weight(1f)
            .alpha(if (enabled) 1f else 0.45f)
            .clip(shape)
            .background(if (filled) colors.threshold else Color.Transparent, shape)
            .then(if (filled) Modifier else Modifier.border(1.dp, colors.raised, shape))
            .clickable(enabled = enabled, role = Role.Button, onClick = onClick)
            .padding(vertical = 10.dp),
    )
}

private fun copyToClipboard(context: Context, text: String) {
    val clipboard = context.getSystemService(Context.CLIPBOARD_SERVICE) as? ClipboardManager ?: return
    clipboard.setPrimaryClip(ClipData.newPlainText("Message", text))
}

/** Opens a web page in the browser (the office's contact form), or a `tel:` link in the dialer. */
internal fun open(context: Context, url: String, action: String = Intent.ACTION_VIEW) {
    try {
        context.startActivity(Intent(action, url.toUri()))
    } catch (_: android.content.ActivityNotFoundException) {
        // Nothing on the device handles it (a tablet with no dialer): nothing to open.
    }
}
